#!/usr/bin/env bash
# Gives macOS builds a stable code signing identity without an Apple Developer
# account. Keychain items are bound to the signing identity; ad hoc builds get
# a new identity on every build, so macOS asks for the keychain password again
# after each rebuild or update. A self-signed certificate keeps the identity
# stable. Gatekeeper is unaffected: the app is still not notarized.
#
# Usage:
#   bash scripts/setup_macos_signing.sh            Use the identity if the login
#                                                  keychain has it, else ad hoc.
#   bash scripts/setup_macos_signing.sh --create   Create the certificate in the
#                                                  login keychain (once per Mac)
#                                                  and export it for CI.
#   CI: set MACOS_SIGNING_P12_BASE64 and MACOS_SIGNING_P12_PASSWORD (the export
#   from --create); the script imports it into a temporary keychain.
#
# Writes macos/Runner/Configs/LocalSigning.xcconfig (ignored by git), which
# AppInfo.xcconfig includes, and prints the identity for scripts that sign
# outside Xcode (export it as MORNYE_CODE_SIGN_IDENTITY).

set -euo pipefail

CERT_NAME="Mornye Local Signing"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
XCCONFIG="$PROJECT_DIR/macos/Runner/Configs/LocalSigning.xcconfig"
EXPORT_DIR="${MORNYE_SIGNING_EXPORT_DIR:-$HOME/.mornye-signing}"
LOGIN_KEYCHAIN="$HOME/Library/Keychains/login.keychain-db"

identity_hash() {
  # SHA-1 of the certificate, so codesign never picks a same-named identity.
  { security find-certificate -c "$CERT_NAME" -Z "$@" 2>/dev/null || true; } |
    awk '/^SHA-1 hash:/ { print $3; exit }'
}

write_xcconfig() {
  local identity="$1"
  cat > "$XCCONFIG" <<EOF
// Generated by scripts/setup_macos_signing.sh. Do not commit.
MORNYE_CODE_SIGN_IDENTITY = $identity
EOF
  echo "$identity"
}

create_certificate() {
  local workdir password
  workdir="$(mktemp -d)"
  trap 'rm -rf "$workdir"' RETURN
  password="$(openssl rand -hex 24)"

  openssl req -x509 -newkey rsa:3072 -sha256 -days 3650 -nodes \
    -subj "/CN=$CERT_NAME" \
    -addext "basicConstraints=critical,CA:false" \
    -addext "keyUsage=critical,digitalSignature" \
    -addext "extendedKeyUsage=critical,codeSigning" \
    -keyout "$workdir/key.pem" -out "$workdir/cert.pem" 2>/dev/null
  # -legacy keeps the PKCS#12 readable by `security import`.
  openssl pkcs12 -export -legacy -name "$CERT_NAME" \
    -inkey "$workdir/key.pem" -in "$workdir/cert.pem" \
    -out "$workdir/signing.p12" -passout "pass:$password"

  security import "$workdir/signing.p12" -k "$LOGIN_KEYCHAIN" \
    -P "$password" -T /usr/bin/codesign -T /usr/bin/security >/dev/null

  mkdir -p "$EXPORT_DIR"
  chmod 700 "$EXPORT_DIR"
  cp "$workdir/signing.p12" "$EXPORT_DIR/signing.p12"
  cp "$workdir/cert.pem" "$EXPORT_DIR/certificate.pem"
  printf '%s\n' "$password" > "$EXPORT_DIR/p12-password.txt"
  chmod 600 "$EXPORT_DIR"/*
  echo "Exported the certificate for CI to $EXPORT_DIR (keep it private)." >&2
}

import_for_ci() {
  local keychain="$RUNNER_TEMP/mornye-signing.keychain-db"
  local keychain_password p12
  keychain_password="$(openssl rand -hex 24)"
  p12="$RUNNER_TEMP/mornye-signing.p12"
  printf '%s' "$MACOS_SIGNING_P12_BASE64" | base64 --decode > "$p12"

  security create-keychain -p "$keychain_password" "$keychain"
  security set-keychain-settings -lut 21600 "$keychain"
  security unlock-keychain -p "$keychain_password" "$keychain"
  security import "$p12" -k "$keychain" -P "$MACOS_SIGNING_P12_PASSWORD" \
    -T /usr/bin/codesign -T /usr/bin/security >/dev/null
  security set-key-partition-list -S apple-tool:,apple:,codesign: -s \
    -k "$keychain_password" "$keychain" >/dev/null
  # Keep the runner's existing keychains searchable.
  local existing=()
  while IFS= read -r line; do
    line="${line#"${line%%[![:space:]]*}"}"
    existing+=("${line//\"/}")
  done < <(security list-keychains -d user)
  security list-keychains -d user -s "$keychain" "${existing[@]}"
  rm -f "$p12"
  identity_hash "$keychain"
}

if [[ -n "${MACOS_SIGNING_P12_BASE64:-}" ]]; then
  : "${MACOS_SIGNING_P12_PASSWORD:?MACOS_SIGNING_P12_PASSWORD is required with MACOS_SIGNING_P12_BASE64}"
  : "${RUNNER_TEMP:?RUNNER_TEMP is required for CI imports}"
  hash="$(import_for_ci)"
  [[ -n "$hash" ]] || { echo "error: the CI certificate did not import." >&2; exit 1; }
  write_xcconfig "$hash"
  exit 0
fi

hash="$(identity_hash "$LOGIN_KEYCHAIN")"
if [[ -z "$hash" && "${1:-}" == "--create" ]]; then
  create_certificate
  hash="$(identity_hash "$LOGIN_KEYCHAIN")"
fi

if [[ -n "$hash" ]]; then
  write_xcconfig "$hash"
else
  rm -f "$XCCONFIG"
  echo "No \"$CERT_NAME\" certificate; builds stay ad hoc. Run with --create to add one." >&2
  echo "-"
fi
